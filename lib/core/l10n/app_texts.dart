String translateAppText(
  BuildContext context,
  String text, {
  Map<String, String> placeholders = const {},
}) {
  final languageCode = Localizations.localeOf(context).languageCode;
  final base = languageCode == 'en' ? (_frToEn[text] ?? text) : text;
  return placeholders.entries.fold<String>(
    base,
    (result, entry) => result.replaceAll('{${entry.key}}', entry.value),
  );
}
